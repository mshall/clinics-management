#!/usr/bin/env bash
# Secrets bootstrap / audit for Kiorly Clinic (read-only unless a step says otherwise). Never prints a secret value.
#
#   scripts/secrets-bootstrap.sh <staging|prod> [--profile <aws-profile>] [--region <r>] [--populate-turn]
#
# Containers are created by OpenTofu (infra/tofu); this script reports which ones still need a human-supplied value (Docs/SECRETS_INVENTORY.md)
# and, with --populate-turn, runs scripts/setup-telehealth-turn.sh (needs CLOUDFLARE_ACCOUNT_ID + CLOUDFLARE_API_TOKEN exported in the shell).
set -euo pipefail
set +x
ENV_NAME="${1:-}"; [ -n "$ENV_NAME" ] || { echo "usage: $0 <staging|prod> [--profile p] [--region r] [--populate-turn]" >&2; exit 2; }
shift
PROFILE_ARGS=(); REGION="${AWS_REGION:-eu-central-1}"; POP_TURN=0
while [ $# -gt 0 ]; do
  case "$1" in
    --profile) shift; PROFILE_ARGS=(--profile "${1:?}");;
    --region) shift; REGION="${1:?}";;
    --populate-turn) POP_TURN=1;;
    *) echo "unknown argument: $1" >&2; exit 2;;
  esac
  shift
done
HERE="$(cd "$(dirname "$0")" && pwd)"
aws_sm() { aws "${PROFILE_ARGS[@]}" --region "$REGION" secretsmanager "$@"; }

# name | who populates it
SECRETS=(
  "kiorly-clinic-${ENV_NAME}/jwt|generated by OpenTofu"
  "/kiorly-clinic/${ENV_NAME}/cloudflare-turn|scripts/setup-telehealth-turn.sh (Cloudflare Realtime TURN key; ADR-039)"
)

printf '%-52s %-10s %s\n' "SECRET" "STATE" "POPULATED BY"
for row in "${SECRETS[@]}"; do
  name="${row%%|*}"; who="${row#*|}"
  if ! aws_sm describe-secret --secret-id "$name" >/dev/null 2>&1; then state="MISSING"
  elif [ "$(aws_sm list-secret-version-ids --secret-id "$name" --query 'length(Versions)' --output text 2>/dev/null || echo 0)" -gt 0 ]; then state="HAS-VALUE"
  else state="EMPTY"; fi
  printf '%-52s %-10s %s\n' "$name" "$state" "$who"
done

if [ "$POP_TURN" -eq 1 ]; then
  "$HERE/setup-telehealth-turn.sh" "$ENV_NAME" "${PROFILE_ARGS[@]}" --region "$REGION"
fi
