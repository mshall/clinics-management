#!/usr/bin/env bash
# Read live AWS stack outputs, verify health, and write local env for optional dev-against-AWS.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

STACK_NAME="${STACK_NAME:-kiorly-clinics-management}"
REGION="${AWS_REGION:-eu-central-1}"
ENV_FILE="${AWS_ENV_FILE:-$ROOT/apps/web/.env.aws}"
OUTPUT_CACHE="${AWS_OUTPUT_CACHE:-$ROOT/.sync/aws-stack.env}"

echo "AWS sync — stack=$STACK_NAME region=$REGION"

if ! command -v aws >/dev/null 2>&1; then
  echo "AWS CLI not found. Install: https://docs.aws.amazon.com/cli/latest/userguide/getting-started-install.html" >&2
  exit 1
fi

ACCOUNT="$(aws sts get-caller-identity --query Account --output text)"
echo "  Account: $ACCOUNT"

APP_URL="$(aws cloudformation describe-stacks \
  --stack-name "$STACK_NAME" \
  --region "$REGION" \
  --query "Stacks[0].Outputs[?OutputKey=='AppUrl'].OutputValue" \
  --output text 2>/dev/null || true)"

if [[ -z "$APP_URL" || "$APP_URL" == "None" ]]; then
  echo "Stack $STACK_NAME has no AppUrl output (not deployed yet?)." >&2
  echo "Deploy: npm run sync:aws:deploy  (or push to main for GitHub Actions)" >&2
  exit 1
fi

APP_URL="${APP_URL%/}"
mkdir -p "$(dirname "$OUTPUT_CACHE")"

cat > "$OUTPUT_CACHE" <<EOF
# Generated by scripts/sync-aws.sh — do not commit (.gitignore)
APP_URL=$APP_URL
AWS_REGION=$REGION
STACK_NAME=$STACK_NAME
SYNCED_AT=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
GIT_COMMIT=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
EOF

mkdir -p "$(dirname "$ENV_FILE")"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/sync-aws.sh — use with: npm run dev:web:aws
# API calls go to CloudFront (SPA + /api/* proxy to App Runner).
VITE_API_URL=$APP_URL
EOF

echo "  AppUrl: $APP_URL"
echo "  Wrote $OUTPUT_CACHE"
echo "  Wrote $ENV_FILE"

if curl -sf "$APP_URL/api/v1/health/live" >/dev/null 2>&1; then
  echo "  Health: OK GET /api/v1/health/live"
else
  echo "  Health: not ready yet — try again after deploy completes" >&2
  exit 1
fi

if [[ "${SYNC_AWS_DEPLOY:-}" == "1" || "${SYNC_AWS_DEPLOY:-}" == "true" ]]; then
  echo "Starting CDK deploy (local)…"
  bash "$ROOT/scripts/deploy-aws.sh"
  bash "$ROOT/scripts/cicd-post-deploy-smoke.sh"
else
  echo ""
  echo "Open live app:     $APP_URL"
  echo "Local UI → AWS API: npm run dev:web:aws"
  echo "Full CDK deploy:   SYNC_AWS_DEPLOY=1 npm run sync:aws"
fi
