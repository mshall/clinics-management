export type MarketStrings = typeof en;
export function marketStrings(lang: string | undefined): MarketStrings {
  return (lang ?? "en").toLowerCase().startsWith("ar") ? ar : en;
}
export function fill(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_m, k) => String(params[k] ?? ""));
}
